const { chromium } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const base = process.env.BASE_URL || "http://127.0.0.1:8080";

(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage(), errors = [], external = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("request", r => { if (!r.url().startsWith(base) && !/^(data:|blob:)/.test(r.url())) external.push(new URL(r.url()).origin); });
  try {
    await page.goto(base);
    await page.waitForSelector("#panel .kpi");
    await page.getByText("Collector: disabled", { exact: false }).waitFor();
    assert.equal(await page.locator("html").getAttribute("lang"), "en");
    assert.equal(await page.locator("#mode-badge").textContent(), "SAMPLE");
    const sample = await (await page.request.get(base + "/api/dataset?mode=SAMPLE")).json();
    const region = sample.Centers.find(r => r.Country === "Region_A").Country;
    await page.locator("#country").selectOption(region);
    const selected = await page.locator("#center option").allTextContents();
    assert.ok(selected.every(label => label === "All centers" || label.includes("Region A")));
    const center = sample.Centers.find(r => r.Country === region).CenterId;
    await page.locator("#center").selectOption(center);
    await page.locator("#model").selectOption("Model Alpha");
    assert.equal(await page.locator("#model-notice").isVisible(), true);
    await page.locator("#start").fill("2026-11-02");
    await page.locator("#start").dispatchEvent("change");
    await page.locator("#end").fill("2026-11-08");
    await page.locator("#end").dispatchEvent("change");
    await page.locator("#tab-models").click();
    await page.getByRole("table", { name: "Exact model identifiers", exact: true }).waitFor();
    const modelRows = await page.getByRole("table", { name: "Exact model identifiers", exact: true }).locator("tbody tr").allTextContents();
    assert.equal(modelRows.length, 1);
    assert.ok(modelRows[0].includes("Model Alpha"));
    await page.locator("#reset").click();
    for (const id of ["users", "daily", "models", "quality", "overview"]) {
      await page.locator(`#tab-${id}`).click();
      assert.equal(await page.locator(`#tab-${id}`).getAttribute("aria-selected"), "true");
      assert.ok((await page.locator("#panel").textContent()).trim().length > 100);
    }
    await page.locator("#tab-users").click();
    await page.locator('[data-search="users"]').fill("demo-user-01");
    assert.equal(await page.getByRole("table", { name: "User detail", exact: true }).locator("tbody tr").count(), 1);
    const csvWait = page.waitForEvent("download");
    await page.locator('[data-csv="users"]').click();
    const csv = await csvWait;
    assert.ok(csv.suggestedFilename().endsWith(".csv"));
    const csvBody = await fs.readFile(await csv.path(), "utf8");
    assert.ok(csvBody.includes('"SAMPLE"') && csvBody.includes("demo-user-01") && !csvBody.includes("demo-user-02"));
    await page.locator("#tab-overview").click();
    for (const type of ["svg", "png"]) {
      const wait = page.waitForEvent("download");
      await page.locator(`[data-chart="activity"][data-format="${type}"]`).click();
      const item = await wait, content = await fs.readFile(await item.path());
      assert.ok(content.length > 200);
      if (type === "svg") assert.ok(content.toString().includes("SAMPLE"));
      else assert.equal(content.subarray(1, 4).toString(), "PNG");
    }
    await page.locator("#real-mode").click();
    await page.locator("#notice").filter({ hasText: /No valid REAL snapshot yet/ }).waitFor();
    assert.equal(await page.locator("#mode-badge").textContent(), "SAMPLE");
    const invalid = { ...sample, Info: [{ ...sample.Info[0], Mode: "UNKNOWN" }] };
    await page.locator("#file-input").setInputFiles({ name: "invalid.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(invalid)) });
    await page.locator("#notice").filter({ hasText: /Import rejected/ }).waitFor();
    assert.equal(await page.locator("#mode-badge").textContent(), "SAMPLE");
    const imported = structuredClone(sample);
    imported.Info[0].Mode = "REAL"; imported.Info[0].Label = "Synthetic REAL import fixture";
    await page.locator("#file-input").setInputFiles({ name: "fixture.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(imported)) });
    await page.locator("#notice").filter({ hasText: /Validated REAL JSON loaded/ }).waitFor();
    assert.equal(await page.locator("#mode-badge").textContent(), "REAL");
    await page.locator("#sample-mode").click();
    let real = structuredClone(imported);
    real.Info[0].AsOf = "2026-11-18T18:00:00Z";
    let failed = false;
    await page.route("**/api/status", route => route.fulfill({ json: { state: failed ? "error" : "ready", lastAttempt: "2026-11-18T19:00:00Z", lastSuccess: real.Info[0].AsOf, lastError: failed ? "Fixture source failed; last valid snapshot unchanged." : null } }));
    await page.route("**/api/dataset?mode=REAL", route => failed ? route.fulfill({ status: 503, json: { error: "Fixture source unavailable" } }) : route.fulfill({ json: real }));
    await page.locator("#real-mode").click();
    await page.waitForFunction(() => document.getElementById("asof").textContent.includes("18:00:00"));
    real.Info[0].AsOf = "2026-11-18T20:00:00Z";
    await page.locator("#refresh").click();
    await page.waitForFunction(() => document.getElementById("asof").textContent.includes("20:00:00"));
    failed = true;
    await page.locator("#refresh").click();
    await page.locator("#notice").filter({ hasText: /Fixture source unavailable/ }).waitFor();
    assert.equal(await page.locator("#mode-badge").textContent(), "REAL");
    assert.ok((await page.locator("#asof").textContent()).includes("20:00:00"));
    failed = false;
    await page.reload();
    await page.waitForFunction(() => document.getElementById("mode-badge").textContent === "REAL");
    await page.locator("#sample-mode").click();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.locator("#theme-toggle").click();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await fs.mkdir(path.join(__dirname, "../artifacts"), { recursive: true });
    await page.screenshot({ path: path.join(__dirname, "../artifacts/sample-dashboard.png"), fullPage: true });
    assert.deepEqual(errors, []);
    assert.deepEqual(external, []);
    console.log("PASS: English UI, all filters/tabs, CSV/SVG/PNG, import, REAL refresh/error retention, responsive layout, no external browser traffic");
  } finally { await browser.close(); }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
